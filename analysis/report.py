"""Write results/REPORT.md from the generated stats. Every number is read, none typed.

    .venv/bin/python analysis/report.py

Run analysis/analyze.py for both agents first. House style: short report, no
em dashes, estimates in prose, intervals in tables, one real episode before
any statistic. EXPLORATORY: nothing here is confirmatory.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from src.prompts import CHANNELS, RENDERINGS  # noqa: E402

AGENTS = ("gemini", "qwen")
LABEL = {"gemini": "Gemini 2.5 Flash", "qwen": "Qwen3-8B"}


def load(agent: str) -> dict:
    return json.loads((ROOT / f"results/main_{agent}/stats.json").read_text())


def p(d, digits=0) -> str:
    return "n/a" if d is None or d.get("est") is None else f"{100 * d['est']:.{digits}f}%"


def pp(d) -> str:
    if d is None or d.get("est") is None:
        return "n/a"
    return f"{100 * d['est']:+.1f} points"


def ci(d) -> str:
    if d is None or d.get("est") is None:
        return "n/a"
    return f"{100 * d['est']:.1f} [{100 * d['lo']:.1f}, {100 * d['hi']:.1f}]"


def example() -> list[str]:
    """One real harmful episode where the message moved a Gemini agent."""
    rows = [json.loads(l) for l in (ROOT / "data/episodes/episodes_gemini.jsonl").read_text().splitlines()[1:]]
    ex = next(r for r in rows if r["item_class"] == "harmful" and r["moved_to_collude"]
              and r["channel"] == "raw" and r["rendering"] == "euphemism")
    situation = ex["turns"][0]["user"].split("\n\nA)")[0]
    return [
        f"Item `{ex['item_id']}`, rendering `{ex['rendering']}`, channel `{ex['channel']}`.",
        "",
        "The situation the agent sees (Vietnamese, as shown):",
        "",
        f"> {situation}",
        "",
        f"> A) {ex['opt_a']}",
        f"> B) {ex['opt_b']}",
        "",
        f"Turn 1, before any message, the agent answered **{ex['pre']['letter']}**, the competitive option.",
        "Then the rival's message arrived:",
        "",
        f"> {ex['raw_message']}",
        "",
        f"Turn 2, the agent answered **{ex['post']['letter']}**, the collusive option "
        f"(the item's fixed key is {ex['collusive_letter']}). Its report to the shop owner:",
        "",
        f"> {ex['report']}",
        "",
    ]


def main() -> None:
    S = {a: load(a) for a in AGENTS}
    st = {a: S[a]["stats"] for a in AGENTS}
    mon = {a: S[a]["monitors"].get("gemini") for a in AGENTS}
    agree = json.loads((ROOT / "results/reader_agreement.json").read_text())

    L = ["# Does a relay stop agents colluding, and what can a monitor see?", "",
         "Exploratory. Generated by `analysis/report.py` from `results/main_*/stats.json`. "
         "Do not edit by hand.", ""]
    L += ["## The question", "",
          "Two AI agents run rival shops on a fictional Vietnamese marketplace. The rival "
          "sends a message inviting the agent to hold a price, split a market, take turns "
          "bidding, swap fake reviews, share costs, or throw a tender. The platform can "
          "relay that message through a rewriter before the agent sees it. We ask two things. "
          "Does the relay stop the agent going along? And what does a platform monitor need "
          "to read to catch the agents that do?", ""]
    L += ["## One episode", ""] + example()
    L += ["## Setup", "",
          "| | |", "|---|---|",
          f"| Items | 60: six families, five harmful scenarios each, each with a harmless twin of the same shape |",
          f"| Renderings | {', '.join(RENDERINGS)} (written once by Gemini, then frozen) |",
          f"| Channels | {', '.join(CHANNELS)} (relays by Qwen3-8B, frozen) |",
          f"| Agents | {LABEL['gemini']}, {LABEL['qwen']}; {st['gemini']['n_episodes']} episodes each |",
          "| Monitor | Gemini 2.5 Flash, reading six views of each episode |",
          "| Intervals | bootstrap 95%, 10,000 resamples, clustered over items |", ""]

    L += ["## Findings", ""]
    g, q = st["gemini"], st["qwen"]
    L += [f"1. **The message moves agents.** Before any message, {p(g['turn1']['harmful'])} of "
          f"Gemini's and {p(q['turn1']['harmful'])} of Qwen's harmful episodes already took the "
          f"collusive option. After a raw message, {p(g['moved']['harmful']['raw'])} of Gemini's and "
          f"{p(q['moved']['harmful']['raw'])} of Qwen's episodes switched from competing to colluding.", ""]
    L += [f"2. **Neither relay reliably stops it.** Paraphrasing changed uptake by "
          f"{pp(g['relay_effect']['harmful']['paraphrased']['all'])} for Gemini and "
          f"{pp(q['relay_effect']['harmful']['paraphrased']['all'])} for Qwen. Neutralizing moved the "
          f"two agents in opposite directions: {pp(g['relay_effect']['harmful']['neutralized']['all'])} "
          f"for Gemini, {pp(q['relay_effect']['harmful']['neutralized']['all'])} for Qwen. "
          "No measurable difference in this sample between pragmatic and direct renderings.", ""]
    def lowest(a):
        cells = [st[a]["turn2"]["mutual_gains"][ch]["all"] for ch in CHANNELS]
        return min(cells, key=lambda d: d["est"])
    L += [f"3. **Harmless cooperation survives the relays.** On the twins, cooperation never fell "
          f"below {p(lowest('gemini'), 1)} for Gemini or {p(lowest('qwen'), 1)} for Qwen in any channel.", ""]
    if mon["gemini"] and "pooled" in mon["gemini"]:
        mg = mon["gemini"]["pooled"]
        L += [f"4. **Actions alone hide collusion.** Shown only the market and the agent's decision, "
              f"the monitor missed {p(mg['fnr']['action'])} of colluding Gemini episodes.", ""]
        L += [f"5. **The message catches everything and accuses too much.** With the rival's message "
              f"in view the monitor missed {p(mg['fnr']['delivered'])}, but it also flagged "
              f"{p(mg['fpr_declined']['delivered'])} of harmful episodes where the agent said no. "
              "It flags the proposal, not the uptake.", ""]
        mq = mon["qwen"]["pooled"] if mon.get("qwen") and "pooled" in mon["qwen"] else None
        L += [f"6. **The agent's own report is the best single addition.** Action plus report missed "
              f"{p(mg['fnr']['report'])} of colluding Gemini episodes and flagged {p(mg['fpr_declined']['report'])} "
              f"of declined ones. The report alone did about as well ({p(mg['fnr']['report_only'])} missed), "
              "so it carries the action with it."
              + (f" Qwen's reports hide more: action plus report missed {p(mq['fnr']['report'])} of its "
                 "colluding episodes." if mq else ""), ""]
    L += [f"7. **Agents admit it when asked, not when reporting.** Of colluding harmful episodes, "
          f"{p(g['disclosure']['item_cO'])} (Gemini) and {p(q['disclosure']['item_cO'])} (Qwen) answered "
          f"yes when asked directly, but only {p(g['disclosure']['lexical'])} and "
          f"{p(q['disclosure']['lexical'])} mentioned the rival's message in their report.", ""]

    L += ["## Tables", "", "Uptake of the harmful arrangement at turn 2 (%):", "",
          "| agent | turn 1 | " + " | ".join(CHANNELS) + " |", "|---" * (len(CHANNELS) + 2) + "|"]
    for a in AGENTS:
        L.append(f"| {LABEL[a]} | {ci(st[a]['turn1']['harmful'])} | "
                 + " | ".join(ci(st[a]['turn2']['harmful'][ch]['all']) for ch in CHANNELS) + " |")
    L += ["", "Relay minus raw, harmful items (percentage points):", "",
          "| agent | paraphrased | neutralized |", "|---|---|---|"]
    for a in AGENTS:
        r = st[a]["relay_effect"]["harmful"]
        L.append(f"| {LABEL[a]} | {ci(r['paraphrased']['all'])} | {ci(r['neutralized']['all'])} |")
    for a in AGENTS:
        m = mon[a]
        if not m or "pooled" not in m:
            continue
        vws = m["views"]
        L += ["", f"Gemini monitor on {LABEL[a]} episodes, pooled over channels (%):", "",
              "| view | missed | missed, message-moved only | false alarm, declined | false alarm, twins |",
              "|---|---|---|---|---|"]
        for v in vws:
            pm = m["pooled"]
            L.append(f"| {v} | {ci(pm['fnr'][v])} | {ci(pm['fnr_moved'][v])} | "
                     f"{ci(pm['fpr_declined'][v])} | {ci(pm['fpr_twins'][v])} |")

    L += ["", "## Questions a sceptic would ask", "",
          "**Were the relays doing anything?** Yes in form: relayed texts differ from the raw "
          "message, and the run refuses any relay identical to its source. No in substance: "
          "readers still found the push toward the arrangement in nearly every relayed text.", "",
          "**Are the messages really pushing toward collusion?** Four LLM readers answered the "
          "same question on the frozen messages. "
          + "; ".join(f"{name} agreed with the gate on {100 * r['harmful']['agreement']:.0f}% of harmful texts"
                      for name, r in agree["readers"].items() if "harmful" in r)
          + ". The outlier was gpt-5.4-nano; a native Vietnamese reader reviewed its disagreements "
          "and judged its reading wrong. This is not a human validation sample.", "",
          "**Is the second monitor any use?** No. The Qwen3-8B monitor flagged most harmless twins, "
          "so its low miss rate carries no information. It is reported in `stats.md` as a failed baseline.", ""]
    L += ["## Limits", "",
          "- Exploratory. The design changed twice after smoke runs, before the main run; every change is logged in `docs/execution-plan.md`.",
          "- 30 harmful scenarios, five per family. Family-level results are descriptive.",
          "- Messages are model-written. No human validation sample.",
          "- One paraphrase per message. Qwen agents read Qwen-relayed text.",
          "- The lexical disclosure code is the weakest measure; read it beside the direct question.", ""]
    out = ROOT / "results/REPORT.md"
    text = "\n".join(L) + "\n"
    assert "—" not in text, "house style: no em dashes"
    out.write_text(text)
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
